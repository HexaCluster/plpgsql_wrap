#!/bin/sh
#
# gen_key_header.sh -- generate wrap_key_data.h from the compile-time key
#
# Usage: gen_key_header.sh <64-hex-char key> <output header>
#
# The key is stored in the .so as two 32-byte arrays (masked key and mask)
# instead of a 64-char hex string literal, so it no longer shows up with
# strings(1).  This is obfuscation only: anyone able to read and reverse
# the .so can still recover the key (see README, "Security notes").
#
# The output file is only rewritten when the key changes, so "make install"
# after "make" does not trigger a rebuild.

set -e

key=$1
out=$2

if [ -z "$out" ]; then
    echo "usage: $0 <64-hex-char key> <output header>" >&2
    exit 1
fi

case "$key" in
    *[!0-9a-fA-F]*|"")
        echo "plpgsql_wrap: WRAP_KEY_HEX must contain only hex characters" >&2
        exit 1 ;;
esac
if [ ${#key} -ne 64 ]; then
    echo "plpgsql_wrap: WRAP_KEY_HEX must be exactly 64 hex chars (got ${#key})" >&2
    exit 1
fi

# Fingerprint of the key, to detect changes without storing it in clear
stamp=$(printf '%s' "$key" | tr 'A-F' 'a-f' | cksum | cut -d' ' -f1)
if [ -f "$out" ] && grep -q "WRAP_KEY_STAMP $stamp " "$out"; then
    exit 0
fi

if [ "$(printf '%s' "$key" | tr -d '0')" = "" ]; then
    echo "WARNING: plpgsql_wrap is being built with the default all-zero key." >&2
    echo "WARNING: wrapped code is NOT protected.  Use make WRAP_KEY_HEX=\$(openssl rand -hex 32)" >&2
fi

mask=$(od -An -tx1 -N32 /dev/urandom | tr -d ' \n')

masked=""
maskbytes=""
i=0
while [ $i -lt 32 ]; do
    k=$(printf '%s' "$key"  | cut -c$((2*i+1))-$((2*i+2)))
    m=$(printf '%s' "$mask" | cut -c$((2*i+1))-$((2*i+2)))
    masked="$masked$(printf '0x%02x,' $(( 0x$k ^ 0x$m )))"
    maskbytes="$maskbytes$(printf '0x%02x,' $(( 0x$m )))"
    i=$((i+1))
done

tmp="$out.tmp.$$"
cat > "$tmp" <<EOF
/* Generated by tools/gen_key_header.sh -- do not edit, do not commit. */
/* WRAP_KEY_STAMP $stamp */
#ifndef WRAP_KEY_DATA_H
#define WRAP_KEY_DATA_H
static const unsigned char wrap_key_masked[32] = { $masked };
static const unsigned char wrap_key_mask[32]   = { $maskbytes };
#endif
EOF
mv "$tmp" "$out"
